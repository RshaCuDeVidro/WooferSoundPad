/// Replaces each "{}" in `template` with the next argument
pub fn format(buf: []u8, template: []const u8, args: anytype) []const u8 {
    var w: std.Io.Writer = .fixed(buf);
    var rest = template;
    inline for (args) |arg| {
        if (std.mem.indexOf(u8, rest, "{}")) |pos| {
            w.writeAll(rest[0..pos]) catch {};
            writeArg(&w, arg);
            rest = rest[pos + 2 ..];
        }
    }
    w.writeAll(rest) catch {};
    return w.buffered();
}

fn writeArg(w: *std.Io.Writer, arg: anytype) void {
    const T = @TypeOf(arg);
    switch (@typeInfo(T)) {
        .int, .comptime_int => w.print("{d}", .{arg}) catch {},
        .float, .comptime_float => w.print("{d:.0}", .{arg}) catch {},
        else => w.writeAll(arg) catch {},
    }
}

test "format templates" {
    var buf: [64]u8 = undefined;
    try std.testing.expectEqualStrings("3 sons", format(&buf, pt.sounds_count, .{3}));
    try std.testing.expectEqualStrings("\"a\" e todos os 2 sons dele serão apagados de vez.", format(&buf, pt.delete_ws_body, .{ "a", 2 }));
}
